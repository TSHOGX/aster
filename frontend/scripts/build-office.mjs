import { build } from 'esbuild';
import { OFFICE_CHANNEL } from '../office/protocol.ts';
import { createHash } from 'node:crypto';
import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve, basename } from 'node:path';
import { patchOfficeViewers } from './patch-office-viewers.mjs';
const root = fileURLToPath(new URL('..', import.meta.url));
const formats = ['document', 'spreadsheet', 'presentation'];
patchOfficeViewers();

// A classic script per format avoids dynamic ES module imports from an opaque
// sandbox (Safari's module/CORS loader has a different lifecycle). Each bundle
// contains only its engine; no user-agent branches or alternate reader paths.
const outputs = await Promise.all(formats.map(async format => {
  const result = await build({
    absWorkingDir: root,
    stdin: { contents: `import { startViewer } from './office/main'; import { createRenderer } from './office/${format}'; startViewer('${format}', createRenderer);`, resolveDir: root, sourcefile: `${format}-entry.ts`, loader: 'ts' },
    outfile: `office-output/${format}.js`, bundle: true, format: 'iife',
    target: ['safari16.4', 'chrome109', 'firefox115'], minify: true,
    drop: ['console'], write: false, legalComments: 'linked',
  });
  return result.outputFiles;
}));
// Report a failed bootstrap before the engine can install its message listener.
// Only a fixed failure code crosses the boundary, never exception or file text.
const bootstrap = `(function(){var channel='${OFFICE_CHANNEL}',token=location.hash.slice(1);window.officeLoadFailed=function(){parent.postMessage({channel:channel,token:token,kind:'failed',reason:'viewer_load_failed'},'*')};window.addEventListener('error',window.officeLoadFailed);parent.postMessage({channel:channel,token:token,kind:'shell-ready'},'*')})()`;
const pages = formats.map(format => ({ name: `${format}.html`, content:
  `<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><link rel="icon" href="data:,"><link rel="stylesheet" href="./${format}.css"><title>Office preview</title><script>${bootstrap}</script></head><body><nav id="navigation" hidden></nav><div id="content" tabindex="-1" data-preview-focus="content" class="office-frame-content"><div id="stage"></div></div><script defer crossorigin="anonymous" src="./${format}.js" onerror="officeLoadFailed()"></script></body></html>` }));
const hash = createHash('sha256');
for (const file of outputs.flat()) hash.update(basename(file.path)).update(file.contents);
for (const page of pages) hash.update(page.name).update(page.content);
const version = hash.digest('hex').slice(0,20);
const folder = resolve(root, 'public/office', version);
await mkdir(folder, { recursive: true });
for (const file of outputs.flat()) await writeFile(resolve(folder, basename(file.path)), file.contents);
for (const page of pages) await writeFile(resolve(folder, page.name), page.content);
await writeFile(resolve(root, 'lib/office-build.ts'), `// Generated by scripts/build-office.mjs.\nexport const OFFICE_VIEWER_ROOT = '/office/${version}';\n`);
