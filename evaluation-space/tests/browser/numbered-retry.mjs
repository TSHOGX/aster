// Two actual native attempts after reconciling a lost known-failure response.
import { chromium, firefox, webkit, expect } from '../../frontend/node_modules/@playwright/test/index.mjs';
import { mkdirSync } from 'node:fs';
import path from 'node:path';
let input = ''; for await (const chunk of process.stdin) input += chunk;
const config = JSON.parse(input);
const browser = await ({ chromium, firefox, webkit }[config.browser]).launch({ headless: true });
const context = await browser.newContext({ ignoreHTTPSErrors: true, viewport: { width: config.width, height: 900 } });
try {
  await context.addCookies([{ name: 'project_login', value: config.cookie, url: config.origin, httpOnly: true, secure: true, sameSite: 'Lax' }]);
  const page = await context.newPage(), errors = []; page.on('pageerror', error => errors.push(error.message));
  const root = `${config.origin}/evaluation-space/api/v1/groups/${config.group}/runs/${config.run}`;
  await page.goto(`${config.origin}/evaluation-space/groups/${config.group}/runs/${config.run}?attempt=${config.failed}`);
  await page.getByRole('link', { name: 'Sign in', exact: true }).click();
  const failed = page.locator(`#attempt-${config.failed}`), succeeded = page.locator(`#attempt-${config.succeeded}`);
  await expect(failed).toHaveAttribute('open', '');
  await expect(failed.locator('summary')).toContainText('retryable_failure');
  await expect(failed.locator('dt').filter({ hasText: /^Attempt$/ }).locator('..')).toHaveText('Attempt1');
  const debug = await (await page.request.get(`${root}/debugger`)).json();
  expect(debug.budget.spent).toEqual({ tokens: 8, cost_micros: 14 });
  expect(debug.budget.held).toEqual({ tokens: 0, cost_micros: 0 });
  const observation = debug.provider_observations.find(value => value.call.id === config.failed);
  expect(observation.outcome.state).toBe('failed'); expect(observation.outcome.retryable).toBe(true);
  const trace = await (await page.request.get(`${root}/artifacts/${observation.outcome.evidence[0].id}`)).json();
  expect(trace.retryable).toBe(true); expect(trace.tool_trace_state).toBe('complete'); expect(trace.tools).toEqual([]);
  await succeeded.locator('summary').press('Enter');
  await expect(succeeded).toHaveAttribute('open', '');
  await expect(succeeded.locator('dt').filter({ hasText: /^Attempt$/ }).locator('..')).toHaveText('Attempt2');
  await expect(succeeded).toContainText('Perform the task and verify the output.');
  await page.reload(); await expect(succeeded).toHaveAttribute('open', '');
  await page.goBack(); await expect(failed).toHaveAttribute('open', '');
  const account = await (await page.request.get(`${config.origin}/api/auth/session`)).json();
  const preferences = await (await page.request.get(`${config.origin}/api/me/preferences`)).json();
  expect((await page.request.patch(`${config.origin}/api/me/preferences`, { headers: { Origin: config.origin }, data: { expected_revision: preferences.revision, language: 'zh' } })).ok()).toBe(true);
  await page.evaluate(id => window.dispatchEvent(new StorageEvent('storage', { key: `account-appearance:${id}` })), account.id);
  await expect(page.locator('html')).toHaveAttribute('lang', 'zh-Hans');
  await expect(failed.locator('summary')).toContainText('retryable_failure');
  await expect(failed.getByText('尝试', { exact: true })).toBeVisible();
  await page.reload(); await expect(failed).toHaveAttribute('open', '');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
  expect(errors).toEqual([]);
  mkdirSync(config.evidence_directory, { recursive: true });
  await page.screenshot({ path: path.join(config.evidence_directory, `attempts-${config.width}.png`), fullPage: true });
  process.stdout.write(`Native numbered retry inspection passed (${config.browser}, ${config.width}px).\n`);
} finally { await context.close(); await browser.close(); }
