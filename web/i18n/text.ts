import { COMMON_ZH } from "./messages";
import { format, type Locale, type Message, type MessageParams } from "./locale";

export type MessageCatalog = Readonly<Record<string, string>>;

/** Translate presentation copy only. Unknown diagnostics and user content pass through. */
export function translateText(locale: Locale, message: Message | undefined, params?: MessageParams, catalog: MessageCatalog = {}, english: MessageCatalog = {}): string {
  if (message && typeof message === "object") { params = message.params; message = message.key; }
  const raw = (message || "").replace(/^(?:Error|APIError): /, "");
  const lookup = (copy: MessageCatalog, key: string) => Object.hasOwn(copy, key) ? copy[key] : undefined;
  if (locale === "en") return format(lookup(english, raw) ?? raw, params);
  const known = lookup(catalog, raw) ?? lookup(COMMON_ZH, raw) ?? lookup(COMMON_ZH, raw.replaceAll(" ", "_"));
  if (known !== undefined) return format(known, params);
  // Admission diagnostics include a stable code followed by a backend cause.
  // Translate only explicitly registered codes; retain unknown diagnostics.
  const admission = raw.match(/^([a-z][a-z_]+): /);
  const reason = admission && lookup(COMMON_ZH, admission[1]);
  if (reason) return format(reason, params);
  // Studio publication findings carry a path and the same validated copy used
  // by its validation panel. Preserve the path verbatim, including Unicode.
  const finding = raw.match(/^(.+): ([^\n]+)$/);
  const detail = finding && lookup(catalog, finding[2]);
  if (detail) return `${finding[1]}：${format(detail, params)}`;
  // Quota messages are generated by web/resource-errors, with validated quantities.
  const quota = raw.match(/^(.+) allowance exceeded\. Limit: (.+); used: (.+); reserved: (.+); requested: (.+)\.$/);
  if (quota) {
    const [, dimension, limit, used, reserved, requested] = quota;
    return `${lookup(COMMON_ZH, dimension) ?? dimension}超出配额。上限：${limit}；已用：${used}；预留：${reserved}；请求：${requested}。`;
  }
  return format(raw, params);
}
